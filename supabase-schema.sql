-- 1. Tabla de Videojuegos (games)
CREATE TABLE IF NOT EXISTS public.games (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  genre TEXT NOT NULL,
  category TEXT NOT NULL,
  platforms TEXT[] NOT NULL DEFAULT '{}',
  rating NUMERIC(2,1) NOT NULL DEFAULT 5.0,
  price NUMERIC(10,2) NOT NULL,
  original_price NUMERIC(10,2) NOT NULL,
  discount INTEGER NOT NULL DEFAULT 0,
  image_url TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabla de Noticias y Novedades (news)
CREATE TABLE IF NOT EXISTS public.news (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  published_date TEXT NOT NULL,
  excerpt TEXT NOT NULL,
  image_url TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Tabla de Suscriptores Club VIP (subscribers)
CREATE TABLE IF NOT EXISTS public.subscribers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  subscribed_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Tabla de Órdenes y Compras (orders)
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name TEXT,
  total NUMERIC(10,2) NOT NULL,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =========================================================
-- HABILITAR SEGURIDAD POR FILAS (Row Level Security - RLS)
-- =========================================================
ALTER TABLE public.games ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.news ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subscribers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura pública para juegos y noticias
CREATE POLICY "Lectura pública de juegos" 
  ON public.games FOR SELECT 
  TO anon, authenticated 
  USING (true);

CREATE POLICY "Lectura pública de noticias" 
  ON public.news FOR SELECT 
  TO anon, authenticated 
  USING (true);

-- Políticas de inserción pública para suscriptores y pedidos
CREATE POLICY "Permitir suscripciones públicas" 
  ON public.subscribers FOR INSERT 
  TO anon, authenticated 
  WITH CHECK (true);

CREATE POLICY "Permitir registrar pedidos" 
  ON public.orders FOR INSERT 
  TO anon, authenticated 
  WITH CHECK (true);

